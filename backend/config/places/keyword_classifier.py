def _dedupe(tags: list[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for tag in tags:
        if tag not in seen:
            seen.add(tag)
            result.append(tag)
    return result


def classify_place(
    title: str,
    category_label: str,
    overview: str,
    addr1: str = "",
    addr2: str = "",
    cat1: str = "",
    cat2: str = "",
    cat3: str = "",
) -> list[str]:
    """
    장소 정보로부터 프로젝트 카테고리 + 세부 키워드 태그 목록을 반환합니다.

    분류 우선순위:
      1. cat3 코드 (가장 세밀)
      2. cat2 코드
      3. cat1 코드
      4. category_label fallback (음식점 → 맛집 등)
      5. 텍스트 키워드 매칭 (title/overview 등)

    반환 형식: [카테고리, 세부키워드, ...]
    여러 카테고리에 중복 분류될 수 있습니다.
    """
    tags: list[str] = []

    # ── 1~3. cat 코드 기반 분류 ──────────────
    for code in (cat3, cat2, cat1):
        code = (code or "").strip()
        if code and code in CAT_CODE_MAP:
            category, sub_keywords = CAT_CODE_MAP[code]
            tags.append(category)
            tags.extend(sub_keywords)

    # ── 4. category_label fallback ──────────
    label = (category_label or "").strip()
    if label in CATEGORY_LABEL_MAP:
        category, sub_keywords = CATEGORY_LABEL_MAP[label]
        tags.append(category)
        tags.extend(sub_keywords)

    # ── 5. 텍스트 키워드 매칭 ────────────────
    source = " ".join(filter(None, [title, category_label, overview, addr1, addr2])).lower()
    for category, keywords in CATEGORY_KEYWORDS.items():
        matched = [kw for kw in keywords if kw in source]
        if matched:
            tags.append(category)
            tags.extend(matched)

    # UI에 노출된 허용 태그만 남김
    return _dedupe([t for t in tags if t in ALLOWED_TAGS])
